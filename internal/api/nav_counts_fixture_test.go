package api

import (
	"bytes"
	"encoding/json"
	"os"
	"path/filepath"
	"testing"

	"github.com/alrayyes/forge-dashboard/internal/dashboard"
	"github.com/stretchr/testify/require"
)

// navCountsFixturePath is the table the e2e specs build their mocked navCounts
// from, in place of a hand-written copy of the counting rule (#1341).
const navCountsFixturePath = "../../tests/generated/nav-counts.json"

// navCountsContribution is what one pull request adds to the badges: the page
// it lands on and which number it raises beside the total ("running", "failed",
// "passed", or "noChecks" for a pull request with no checks). Page is empty
// when the badges leave it out (a draft or a hidden one). Behind is 1 when it
// also raises the page's behind count (#4629), which sits beside State: a
// pull request behind its base branch, with something left to merge.
type navCountsContribution struct {
	Kind       string `json:"kind"`
	CI         string `json:"ci"`
	Draft      bool   `json:"draft"`
	Hidden     bool   `json:"hidden"`
	BehindBase bool   `json:"behindBase"`
	Empty      bool   `json:"empty"`
	Page       string `json:"page"`
	State      string `json:"state"`
	Behind     int    `json:"behind"`
}

type navCountsFixture struct {
	Note         string                  `json:"note"`
	PullRequests []navCountsContribution `json:"pullRequests"`
}

// contributionOf runs the server's own buildNavCounts on the one item and reads
// the answer back through its JSON, so a renamed field changes the table.
func contributionOf(t *testing.T, counts navCounts) (page, state string, behind int) {
	t.Helper()

	raw, err := json.Marshal(counts)
	require.NoError(t, err)
	var pages map[string]map[string]int
	require.NoError(t, json.Unmarshal(raw, &pages))

	for name, numbers := range pages {
		if numbers["total"] != 1 {
			continue
		}
		page, state, behind = name, "none", numbers["behind"]
		for key, n := range numbers {
			// Behind sits beside the CI state, not instead of it.
			if key != "total" && key != "behind" && n == 1 {
				state = key
			}
		}
	}

	return page, state, behind
}

// navCountsFixtureViews is every combination of kind, CI state, draft and
// hidden, level with its base, then every one behind it with and without
// something left to merge (#4629).
func navCountsFixtureViews() []pullRequestView {
	kinds := []dashboard.PullRequestKind{dashboard.KindRegular, dashboard.KindRelease, dashboard.KindDependency}
	cis := []dashboard.CIStatus{dashboard.CINone, dashboard.CIPending, dashboard.CISuccess, dashboard.CIFailure, dashboard.CICancelled}
	// behind, empty: an empty one is only interesting when it is behind.
	bases := [][2]bool{{false, false}, {true, false}, {true, true}}

	var views []pullRequestView
	for _, kind := range kinds {
		for _, ci := range cis {
			for _, flags := range [][2]bool{{false, false}, {false, true}, {true, false}, {true, true}} {
				for _, base := range bases {
					view := pullRequestView{Kind: kind}
					view.CI, view.Draft, view.Hidden = ci, flags[0], flags[1]
					view.Behind, view.Empty = base[0], base[1]
					views = append(views, view)
				}
			}
		}
	}

	return views
}

func buildNavCountsFixture(t *testing.T) []byte {
	t.Helper()

	file := navCountsFixture{
		Note: "Generated by internal/api/nav_counts_fixture_test.go from buildNavCounts. Do not edit: run " +
			"UPDATE_FIXTURES=1 go test ./internal/api -run TestNavCountsFixture.",
	}
	for _, view := range navCountsFixtureViews() {
		page, state, behind := contributionOf(t, buildNavCounts([]pullRequestView{view}, 0))
		file.PullRequests = append(file.PullRequests, navCountsContribution{
			Kind: string(view.Kind), CI: string(view.CI), Draft: view.Draft, Hidden: view.Hidden,
			BehindBase: view.Behind, Empty: view.Empty, Page: page, State: state, Behind: behind,
		})
	}

	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	require.NoError(t, enc.Encode(file))

	return buf.Bytes()
}

// The e2e specs mock /api/v1/dashboard and fill each snapshot's navCounts from this
// table, so they can't pass against a counting rule the server no longer has. A
// change to the rule, or a renamed field, fails here until the table is
// regenerated and committed (#1341).
func TestNavCountsFixture_IsCurrent(t *testing.T) {
	t.Parallel()

	want := buildNavCountsFixture(t)
	path := filepath.Clean(navCountsFixturePath)

	if os.Getenv("UPDATE_FIXTURES") != "" {
		require.NoError(t, os.WriteFile(path, want, 0o600))

		return
	}

	got, err := os.ReadFile(path)
	require.NoError(t, err, "the fixture is missing: run UPDATE_FIXTURES=1 go test ./internal/api -run TestNavCountsFixture")
	require.True(t, bytes.Equal(want, got),
		"tests/generated/nav-counts.json is stale: run UPDATE_FIXTURES=1 go test ./internal/api -run TestNavCountsFixture and commit the result")
}
