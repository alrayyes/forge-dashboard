package api

import (
	"bytes"
	"encoding/json"
	"os"
	"path/filepath"
	"testing"

	"github.com/alrayyes/forge-dashboard/internal/dashboard"
	"github.com/stretchr/testify/require"
)

// navCountsFixturePath is the table the e2e specs build their mocked navCounts
// from, in place of a hand-written copy of the counting rule (#1341).
const navCountsFixturePath = "../../tests/generated/nav-counts.json"

// navCountsContribution is what one pull request adds to the badges: the page
// it lands on and which number it raises beside the total ("running", "failed",
// "passed", or "none" for a pull request with no checks). Page is empty when
// the badges leave it out (a draft or a hidden one).
type navCountsContribution struct {
	Kind   string `json:"kind"`
	CI     string `json:"ci"`
	Draft  bool   `json:"draft"`
	Hidden bool   `json:"hidden"`
	Page   string `json:"page"`
	State  string `json:"state"`
}

// navCountsBranch is what one default branch adds to the Branches badge.
type navCountsBranch struct {
	Status string `json:"status"`
	State  string `json:"state"`
}

type navCountsFixture struct {
	Note         string                  `json:"note"`
	PullRequests []navCountsContribution `json:"pullRequests"`
	Branches     []navCountsBranch       `json:"branches"`
}

// contributionOf runs the server's own buildNavCounts on the one item and reads
// the answer back through its JSON, so a renamed field changes the table.
func contributionOf(t *testing.T, counts navCounts) (page, state string) {
	t.Helper()

	raw, err := json.Marshal(counts)
	require.NoError(t, err)
	var pages map[string]map[string]int
	require.NoError(t, json.Unmarshal(raw, &pages))

	for name, numbers := range pages {
		if numbers["total"] != 1 {
			continue
		}
		page, state = name, "none"
		for key, n := range numbers {
			if key != "total" && n == 1 {
				state = key
			}
		}
	}

	return page, state
}

func buildNavCountsFixture(t *testing.T) []byte {
	t.Helper()

	file := navCountsFixture{
		Note: "Generated by internal/api/nav_counts_fixture_test.go from buildNavCounts. Do not edit: run " +
			"UPDATE_FIXTURES=1 go test ./internal/api -run TestNavCountsFixture.",
	}
	for _, kind := range []dashboard.PullRequestKind{dashboard.KindRegular, dashboard.KindRelease, dashboard.KindDependency} {
		for _, ci := range []dashboard.CIStatus{dashboard.CINone, dashboard.CIPending, dashboard.CISuccess, dashboard.CIFailure} {
			for _, draft := range []bool{false, true} {
				for _, hidden := range []bool{false, true} {
					view := pullRequestView{Kind: kind}
					view.CI, view.Draft, view.Hidden = ci, draft, hidden
					page, state := contributionOf(t, buildNavCounts([]pullRequestView{view}, 0, nil))
					file.PullRequests = append(file.PullRequests, navCountsContribution{
						Kind: string(kind), CI: string(ci), Draft: draft, Hidden: hidden, Page: page, State: state,
					})
				}
			}
		}
	}
	for _, status := range []dashboard.MainBranchStatus{
		dashboard.MainBranchNone, dashboard.MainBranchRunning, dashboard.MainBranchPassed, dashboard.MainBranchFailed,
	} {
		_, state := contributionOf(t, buildNavCounts(nil, 0, []dashboard.MainBranch{{Status: status}}))
		file.Branches = append(file.Branches, navCountsBranch{Status: string(status), State: state})
	}

	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	require.NoError(t, enc.Encode(file))

	return buf.Bytes()
}

// The e2e specs mock /api/dashboard and fill each snapshot's navCounts from this
// table, so they can't pass against a counting rule the server no longer has. A
// change to the rule, or a renamed field, fails here until the table is
// regenerated and committed (#1341).
func TestNavCountsFixture_IsCurrent(t *testing.T) {
	t.Parallel()

	want := buildNavCountsFixture(t)
	path := filepath.Clean(navCountsFixturePath)

	if os.Getenv("UPDATE_FIXTURES") != "" {
		require.NoError(t, os.WriteFile(path, want, 0o600))

		return
	}

	got, err := os.ReadFile(path)
	require.NoError(t, err, "the fixture is missing: run UPDATE_FIXTURES=1 go test ./internal/api -run TestNavCountsFixture")
	require.True(t, bytes.Equal(want, got),
		"tests/generated/nav-counts.json is stale: run UPDATE_FIXTURES=1 go test ./internal/api -run TestNavCountsFixture and commit the result")
}
