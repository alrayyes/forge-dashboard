// behindStatusFixturePath is the pull request list the behind status specs
// render, in place of a hand-written payload (#3601).
const behindStatusFixturePath = "../../tests/generated/behind-status.json"

// behindStatusPullRequests builds the armed, behind pull request the server
// sends where the base branch requires up-to-date branches, and the same one
// where it does not, through the same view the dashboard endpoint serves.
func behindStatusPullRequests(t *testing.T) map[string]json.RawMessage {
	t.Helper()

	at := time.Date(2026, 11, 1, 12, 0, 0, 0, time.UTC)
	armed := true
	build := func(requiresUpToDate bool) dashboard.PullRequest {
		// Where being behind is no hold, the real hold is a cancelled run.
		ci := dashboard.CISuccess
		if !requiresUpToDate {
			ci = dashboard.CICancelled
		}

		return dashboard.PullRequest{
			Forge: dashboard.ForgeGitHub, Repo: "alrayyes/forge-dashboard", Number: 3417,
			Title: "An armed pull request that is behind", URL: "https://example.com/3417",
			Author: "claude", CI: ci, CreatedAt: at, UpdatedAt: at,
			MergeStatus: dashboard.MergeMergeable, BaseBranch: "main",
			Behind: true, BaseRequiresUpToDate: &requiresUpToDate, AutoMergeEnabled: &armed,
		}
	}

	out := map[string]json.RawMessage{}
	for name, requires := range map[string]bool{"strict": true, "notStrict": false} {
		views, _, _ := boardSettings{now: at}.pullRequestViews([]dashboard.PullRequest{build(requires)}, boardView{})
		require.Len(t, views, 1)
		raw, err := json.Marshal(views[0])
		require.NoError(t, err)
		out[name] = raw
	}

	return out
}

func buildBehindStatusFixture(t *testing.T) []byte {
	t.Helper()

	file := struct {
		Note string                     `json:"note"`
		PRs  map[string]json.RawMessage `json:"pullRequests"`
	}{
		Note: "Generated by internal/api/behind_status_fixture_test.go from the dashboard's own pull request view. " +
			"Do not edit: run UPDATE_FIXTURES=1 go test ./internal/api -run TestBehindStatusFixture.",
		PRs: behindStatusPullRequests(t),
	}

	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	require.NoError(t, enc.Encode(file))

	return buf.Bytes()
}

// Where the base branch requires up-to-date branches the payload says the pull
// request waits for the branch to be updated, and offers Update branch.
// Where it does not, being behind is not blamed.
func TestBehindStatusFixture_SaysWhatHoldsTheBranch(t *testing.T) {
	t.Parallel()

	prs := behindStatusPullRequests(t)

	var strict, loose struct {
		Behind    bool `json:"behind"`
		AutoMerge struct {
			State string `json:"state"`
			Code  string `json:"code"`
		} `json:"autoMerge"`
		AllowedActions []struct {
			Action string `json:"action"`
		} `json:"allowedActions"`
	}
	require.NoError(t, json.Unmarshal(prs["strict"], &strict))
	require.NoError(t, json.Unmarshal(prs["notStrict"], &loose))

	assert.True(t, strict.Behind)
	assert.Equal(t, "waiting", strict.AutoMerge.State)
	assert.Equal(t, "behind", strict.AutoMerge.Code)
	var offered []string
	for _, a := range strict.AllowedActions {
		offered = append(offered, a.Action)
	}
	assert.Contains(t, offered, "update_branch")

	assert.Equal(t, "checks_pending", loose.AutoMerge.Code, "being behind is not blamed")
}

// The specs render this file, so they can't pass against a payload the server
// no longer builds. A change to what the server sends fails here until the
// file is regenerated and committed (#3601).
func TestBehindStatusFixture_IsCurrent(t *testing.T) {
	t.Parallel()

	want := buildBehindStatusFixture(t)
	path := filepath.Clean(behindStatusFixturePath)

	if os.Getenv("UPDATE_FIXTURES") != "" {
		require.NoError(t, os.WriteFile(path, want, 0o600))

		return
	}

	got, err := os.ReadFile(path)
	require.NoError(t, err, "the fixture is missing: run UPDATE_FIXTURES=1 go test ./internal/api -run TestBehindStatusFixture")
	require.True(t, bytes.Equal(want, got),
		"tests/generated/behind-status.json is stale: run UPDATE_FIXTURES=1 go test ./internal/api -run TestBehindStatusFixture and commit the result")
}
