package dashboard_test

import (
	"bytes"
	"encoding/json"
	"os"
	"path/filepath"
	"testing"

	"github.com/alrayyes/forge-dashboard/internal/dashboard"
	"github.com/stretchr/testify/require"
)

// forgeCapabilitiesFixturePath is the table the e2e specs build a mocked forge
// entry's `capabilities` from, in place of a hand-written copy.
const forgeCapabilitiesFixturePath = "../../tests/generated/forge-capabilities.json"

type forgeCapabilitiesFixture struct {
	Note   string                                 `json:"note"`
	Forges map[string]dashboard.ForgeCapabilities `json:"forges"`
}

func buildForgeCapabilitiesFixture(t *testing.T) []byte {
	t.Helper()

	file := forgeCapabilitiesFixture{
		Note: "Generated by internal/dashboard/forge_capabilities_fixture_test.go from capabilitiesByForge. Do not edit: run " +
			"UPDATE_FIXTURES=1 go test ./internal/dashboard -run TestForgeCapabilitiesFixture.",
		Forges: map[string]dashboard.ForgeCapabilities{},
	}
	for _, forge := range []dashboard.Forge{dashboard.ForgeGitHub, dashboard.ForgeForgejo} {
		caps, ok := dashboard.CapabilitiesOf(forge)
		require.True(t, ok, "no capabilities for %s", forge)
		file.Forges[string(forge)] = caps
	}

	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	require.NoError(t, enc.Encode(file))

	return buf.Bytes()
}

// The e2e specs mock a forge entry's `capabilities` from this table, so they
// can't pass against a forge the server describes differently. A change to the
// capabilities table or a renamed field fails here until the table is
// regenerated and committed.
func TestForgeCapabilitiesFixture_IsCurrent(t *testing.T) {
	t.Parallel()

	want := buildForgeCapabilitiesFixture(t)
	path := filepath.Clean(forgeCapabilitiesFixturePath)

	if os.Getenv("UPDATE_FIXTURES") != "" {
		require.NoError(t, os.WriteFile(path, want, 0o600))

		return
	}

	got, err := os.ReadFile(path)
	require.NoError(t, err, "the fixture is missing: run UPDATE_FIXTURES=1 go test ./internal/dashboard -run TestForgeCapabilitiesFixture")
	require.True(t, bytes.Equal(want, got),
		"tests/generated/forge-capabilities.json is stale: run UPDATE_FIXTURES=1 go test ./internal/dashboard -run TestForgeCapabilitiesFixture and commit the result")
}
