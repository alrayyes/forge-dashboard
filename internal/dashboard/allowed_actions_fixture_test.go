package dashboard_test

import (
	"bytes"
	"encoding/json"
	"os"
	"path/filepath"
	"testing"

	"github.com/alrayyes/forge-dashboard/internal/dashboard"
	"github.com/stretchr/testify/require"
)

// stackedParentSentinel stands in for the parent's number in the one message
// that carries it ("Stacked on #N"). The browser side puts the mocked pull
// request's own parent number in its place.
const stackedParentSentinel = 999999999

// fixturePath is the table the e2e specs read in place of a hand-written copy of
// the rules (#1437).
const fixturePath = "../../tests/generated/allowed-actions.json"

// axis is one input the rules read, and the values the table covers for it. The
// browser side maps a mocked pull request's fields onto these values by name.
type axis struct {
	Name   string   `json:"name"`
	Values []string `json:"values"`
}

// fixtureOutput is what the server puts on a pull request for one combination
// of inputs: allowedActions, status and kind, as the API serialises them.
type fixtureOutput struct {
	AllowedActions []dashboard.ActionAvailability `json:"allowedActions"`
	Status         *dashboard.Blocked             `json:"status"`
	Kind           dashboard.PullRequestKind      `json:"kind"`
}

type fixtureFile struct {
	Note    string          `json:"note"`
	Axes    []axis          `json:"axes"`
	Outputs []fixtureOutput `json:"outputs"`
	// Table holds, for each combination in mixed-radix order over Axes (the
	// first axis varying slowest), the index of its entry in Outputs.
	Table []int `json:"table"`
}

var fixtureAxes = []axis{
	{"forge", []string{"github", "forgejo"}},
	{"author", []string{"person", "dependabot", "renovate"}},
	{"release", []string{"no", "yes"}},
	{"empty", []string{"no", "yes"}},
	{"behind", []string{"no", "yes"}},
	{"draft", []string{"no", "yes"}},
	{"ci", []string{"none", "pending", "success", "failure"}},
	{"mergeStatus", []string{"mergeable", "blocked", "conflicting", "unstable", "unknown"}},
	{"autoMergeEnabled", []string{"off", "on"}},
	{"autoMergeAllowed", []string{"yes", "no"}},
	{"stacked", []string{"no", "yes"}},
}

// pullRequestFor builds the pull request one combination of axis values stands
// for. Anything the rules don't read stays at its zero value.
func pullRequestFor(v map[string]string) dashboard.PullRequest {
	pr := dashboard.PullRequest{
		Forge:       dashboard.Forge(v["forge"]),
		Repo:        "o/r",
		Number:      1,
		Author:      "alice",
		Empty:       v["empty"] == "yes",
		Behind:      v["behind"] == "yes",
		Draft:       v["draft"] == "yes",
		CI:          dashboard.CIStatus(v["ci"]),
		MergeStatus: dashboard.MergeStatus(v["mergeStatus"]),
	}
	switch v["author"] {
	case "dependabot", "renovate":
		pr.Author = v["author"]
	}
	if v["release"] == "yes" {
		pr.Labels = []dashboard.Label{{Name: "autorelease: pending"}}
	}
	if v["autoMergeEnabled"] == "on" {
		on := true
		pr.AutoMergeEnabled = &on
	}
	if v["autoMergeAllowed"] == "no" {
		no := false
		pr.AutoMergeAllowed = &no
	}
	if v["stacked"] == "yes" {
		pr.StackedOn = &dashboard.StackRef{Number: stackedParentSentinel}
	}

	return pr
}

func buildAllowedActionsFixture(t *testing.T) []byte {
	t.Helper()

	file := fixtureFile{
		Note: "Generated by internal/dashboard/allowed_actions_fixture_test.go from the Go rules " +
			"(AllowedActions, PullRequestStatus, KindOf). Do not edit: run " +
			"UPDATE_FIXTURES=1 go test ./internal/dashboard -run TestAllowedActionsFixture. " +
			"#999999999 in a message stands for the stacked-on pull request's number.",
		Axes: fixtureAxes,
	}
	seen := map[string]int{}

	var walk func(i int, chosen map[string]string)
	walk = func(i int, chosen map[string]string) {
		if i == len(fixtureAxes) {
			pr := pullRequestFor(chosen)
			actions := dashboard.AllowedActions(pr, nil)
			out := fixtureOutput{
				AllowedActions: actions,
				Status:         dashboard.PullRequestStatus(pr, actions),
				Kind:           dashboard.KindOf(pr, nil),
			}
			key, err := json.Marshal(out)
			require.NoError(t, err)
			idx, ok := seen[string(key)]
			if !ok {
				idx = len(file.Outputs)
				seen[string(key)] = idx
				file.Outputs = append(file.Outputs, out)
			}
			file.Table = append(file.Table, idx)

			return
		}
		for _, value := range fixtureAxes[i].Values {
			chosen[fixtureAxes[i].Name] = value
			walk(i+1, chosen)
		}
	}
	walk(0, map[string]string{})

	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	require.NoError(t, enc.Encode(file))

	return buf.Bytes()
}

// The e2e specs mock /api/dashboard and fill each pull request's
// allowedActions, status and kind from this table, so they can't pass against
// a rule the server no longer has. A change to the rules fails here until the
// table is regenerated and committed (#1437).
func TestAllowedActionsFixture_IsCurrent(t *testing.T) {
	t.Parallel()

	want := buildAllowedActionsFixture(t)
	path := filepath.Clean(fixturePath)

	if os.Getenv("UPDATE_FIXTURES") != "" {
		require.NoError(t, os.WriteFile(path, want, 0o600))

		return
	}

	got, err := os.ReadFile(path)
	require.NoError(t, err, "the fixture is missing: run UPDATE_FIXTURES=1 go test ./internal/dashboard -run TestAllowedActionsFixture")
	require.True(t, bytes.Equal(want, got),
		"tests/generated/allowed-actions.json is stale: run UPDATE_FIXTURES=1 go test ./internal/dashboard -run TestAllowedActionsFixture and commit the result")
}
