func TestParseTOMLLocks_NothingPublicIsAnErrorAndGarbageIsToo(t *testing.T) {
	t.Parallel()

	_, err := osv.ParseCargoLock([]byte("[[package]]\nname = \"corp\"\nversion = \"1.0.0\"\nsource = \"registry+https://crates.example.com/index\"\n"))
	require.ErrorIs(t, err, osv.ErrNoPublicPackages)

	got, err := osv.ParseCargoLock([]byte("version = 3\n\n[[package]]\nname = \"app\"\nversion = \"0.1.0\"\n"))
	require.NoError(t, err)
	assert.Empty(t, got, "a workspace with no dependencies is a known zero")

	for _, parse := range []func([]byte) ([]osv.Package, error){osv.ParseCargoLock, osv.ParseUvLock, osv.ParsePoetryLock} {
		_, err := parse([]byte("{\"not\": \"toml\"}"))
		require.Error(t, err)
		_, err = parse(nil)
		require.Error(t, err)
	}
}

func TestParseNPMLock_ReadsVersionOneAndLaterFiles(t *testing.T) {
	t.Parallel()

	v1 := `{"lockfileVersion":1,"requires":true,"dependencies":{
		"left-pad":{"version":"1.3.0","resolved":"https://registry.npmjs.org/left-pad/-/left-pad-1.3.0.tgz","requires":{"x":"^1"},
			"dependencies":{"nested":{"version":"2.0.0","resolved":"https://registry.npmjs.org/nested/-/nested-2.0.0.tgz","dev":true}}},
		"@scope/b":{"version":"2.0.1","resolved":"https://registry.yarnpkg.com/@scope/b/-/b-2.0.1.tgz"},
		"my-lodash":{"version":"npm:lodash@4.17.0","resolved":"https://registry.npmjs.org/lodash/-/lodash-4.17.0.tgz"},
		"gitdep":{"version":"github:user/repo#abc"},
		"private":{"version":"1.0.0","resolved":"https://npm.example.com/private/-/private-1.0.0.tgz"}}}`

	got, err := osv.ParseNPMLock([]byte(v1))
	require.NoError(t, err)
	assert.ElementsMatch(t, []osv.Package{
		{Ecosystem: "npm", Name: "left-pad", Version: "1.3.0"},
		{Ecosystem: "npm", Name: "nested", Version: "2.0.0"},
		{Ecosystem: "npm", Name: "@scope/b", Version: "2.0.1"},
		{Ecosystem: "npm", Name: "lodash", Version: "4.17.0"},
	}, got)

	got, err = osv.ParseNPMLock([]byte(lockJSONForNPM))
	require.NoError(t, err)
	assert.Equal(t, []osv.Package{{Ecosystem: "npm", Name: "left-pad", Version: "1.3.0"}}, got)

	_, err = osv.ParseNPMLock([]byte(`{"lockfileVersion":1,"dependencies":{"p":{"version":"1.0.0","resolved":"https://npm.example.com/p/-/p-1.0.0.tgz"}}}`))
	require.ErrorIs(t, err, osv.ErrNoPublicPackages)

	_, err = osv.ParseNPMLock([]byte(`{"name":"x"}`))
	require.Error(t, err)
	_, err = osv.ParseNPMLock([]byte(`nope`))
	require.Error(t, err)

	got, err = osv.ParseNPMLock([]byte(`{"lockfileVersion":1,"dependencies":{}}`))
	require.NoError(t, err)
	assert.Empty(t, got)
}

const lockJSONForNPM = `{"lockfileVersion":3,"packages":{"":{},"node_modules/left-pad":{"version":"1.3.0","resolved":"https://registry.npmjs.org/left-pad/-/left-pad-1.3.0.tgz"}}}`

