func TestParseBunLock_ReadsRegistryPackagesFromJSONC(t *testing.T) {
	t.Parallel()

	lock := `{
  // bun writes comments and trailing commas
  "lockfileVersion": 1,
  "workspaces": { "": { "name": "app" } },
  "packages": {
    "left-pad": ["left-pad@1.3.0", "", {}, "sha512-aaa"],
    "@scope/b": ["@scope/b@2.0.1", "", { "dependencies": { "c": "^1" } }, "sha512-bbb"],
    "my-lodash": ["my-lodash@npm:lodash@4.17.0", "", {}, "sha512-ccc"],
    "private": ["private@1.0.0", "https://npm.example.com/", {}, "sha512-ddd"],
    "gitdep": ["gitdep@github:user/repo#abc123", {}, "user-repo-abc123"],
    "local": ["local@workspace:packages/local"],
  },
}`

	got, err := osv.ParseBunLock([]byte(lock))
	require.NoError(t, err)
	assert.ElementsMatch(t, []osv.Package{
		{Ecosystem: "npm", Name: "left-pad", Version: "1.3.0"},
		{Ecosystem: "npm", Name: "@scope/b", Version: "2.0.1"},
		{Ecosystem: "npm", Name: "lodash", Version: "4.17.0"},
	}, got)
}

func TestParseBunLock_RefusesWhatItCannotRead(t *testing.T) {
	t.Parallel()

	_, err := osv.ParseBunLock([]byte(`{"lockfileVersion":1}`))
	require.Error(t, err)
	_, err = osv.ParseBunLock([]byte(`not json`))
	require.Error(t, err)
	_, err = osv.ParseBunLock([]byte(`{"packages":{"p":["p@1.0.0","https://npm.example.com/",{}]}}`))
	require.ErrorIs(t, err, osv.ErrNoPublicPackages)
}

func TestParseComposerLock_ReadsPackagesAndDevPackages(t *testing.T) {
	t.Parallel()

	lock := `{"packages":[
		{"name":"monolog/monolog","version":"3.5.0"},
		{"name":"symfony/console","version":"v6.4.1"},
		{"name":"acme/branch","version":"dev-main"}],
	"packages-dev":[{"name":"phpunit/phpunit","version":"10.5.0"}]}`

	got, err := osv.ParseComposerLock([]byte(lock))
	require.NoError(t, err)
	assert.ElementsMatch(t, []osv.Package{
		{Ecosystem: "Packagist", Name: "monolog/monolog", Version: "3.5.0"},
		{Ecosystem: "Packagist", Name: "symfony/console", Version: "6.4.1"},
		{Ecosystem: "Packagist", Name: "phpunit/phpunit", Version: "10.5.0"},
	}, got)
}

func TestParseComposerLock_RefusesWhatItCannotRead(t *testing.T) {
	t.Parallel()

	_, err := osv.ParseComposerLock([]byte(`{"content-hash":"x"}`))
	require.Error(t, err, "no package lists is not a lock file")
	_, err = osv.ParseComposerLock([]byte(`nope`))
	require.Error(t, err)

	got, err := osv.ParseComposerLock([]byte(`{"packages":[],"packages-dev":[]}`))
	require.NoError(t, err)
	assert.Empty(t, got)
}

